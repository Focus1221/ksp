import streamlit as st
import google.generativeai as genai

# --- НАСТРОЙКИ СТРАНИЦЫ ---
st.set_page_config(page_title="Генератор КСП", page_icon="📚", layout="centered")

# --- БОКОВАЯ ПАНЕЛЬ ДЛЯ НАСТРОЕК ---
st.sidebar.header("Настройки ИИ")
st.sidebar.write("Для работы нужен бесплатный API ключ от Google Gemini.")
api_key = st.sidebar.text_input("Введите ваш API ключ:", type="password")
st.sidebar.markdown("[Получить ключ здесь](https://aistudio.google.com/app/apikey)")

# --- ОСНОВНОЙ ИНТЕРФЕЙС ---
st.title("📚 Генератор КСП (Краткосрочного плана)")
st.write("Заполните данные ниже, и ИИ создаст черновик краткосрочного плана урока.")

# Форма ввода данных
with st.form("ksp_form"):
    subject = st.text_input("Предмет", placeholder="Например: Информатика")
    grade = st.text_input("Класс", placeholder="Например: 8 класс")
    topic = st.text_input("Тема урока", placeholder="Например: Циклы for и while в Python")
    learning_goals = st.text_area(
        "Цели обучения (из учебной программы)", 
        placeholder="Например: 8.3.3.1 Использовать циклы в программировании"
    )
    duration = st.selectbox("Продолжительность урока", ["45 минут", "40 минут", "90 минут"])
    
    # Кнопка отправки
    submitted = st.form_submit_button("Сгенерировать КСП")

# --- ЛОГИКА ГЕНЕРАЦИИ ---
if submitted:
    if not api_key:
        st.error("Пожалуйста, введите API ключ в боковой панели слева!")
    elif not subject or not topic or not learning_goals:
        st.warning("Пожалуйста, заполните основные поля (Предмет, Тема, Цели обучения).")
    else:
        # Настройка ИИ
        genai.configure(api_key=api_key)
        # Используем быструю и бесплатную модель
        model = genai.GenerativeModel('gemini-1.5-flash') 

        # Формируем промпт (запрос) для ИИ с педагогической структурой
        prompt = f"""
        Ты — опытный методист и учитель. Твоя задача — составить качественный краткосрочный план (КСП) урока.
        
        Вводные данные:
        - Предмет: {subject}
        - Класс: {grade}
        - Тема урока: {topic}
        - Цели обучения: {learning_goals}
        - Время: {duration}

        Структурируй КСП по следующим разделам (используй стандарты СМК РК):
        1. Цели урока (Все учащиеся смогут..., Большинство смогут..., Некоторые смогут...).
        2. Критерии оценивания.
        3. Языковые цели (ключевые слова и фразы).
        4. Привитие ценностей.
        5. Межпредметные связи.
        6. Ход урока в виде таблицы или четкого списка по этапам:
           - Начало урока (Орг. момент, актуализация знаний) - укажи примерное время.
           - Середина урока (Изучение нового материала, практические задания с дескрипторами) - укажи примерное время.
           - Конец урока (Рефлексия, домашнее задание) - укажи примерное время.
        
        Пиши профессиональным педагогическим языком, четко и структурировано. Форматируй текст с помощью Markdown (жирный текст, списки).
        """

        with st.spinner("ИИ генерирует КСП... Это займет несколько секунд."):
            try:
                # Отправка запроса к ИИ
                response = model.generate_content(prompt)
                
                # Вывод результата
                st.success("КСП успешно сгенерирован!")
                st.markdown("---")
                st.markdown(response.text)
                
                # Кнопка для скачивания результата
                st.download_button(
                    label="Скачать КСП как текстовый файл",
                    data=response.text,
                    file_name="KSP_uroka.txt",
                    mime="text/plain"
                )

            except Exception as e:
                st.error(f"Произошла ошибка при генерации: {e}")
